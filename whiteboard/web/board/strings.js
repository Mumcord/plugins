/**
 * Makes the text lookup for one strings map. Unknown keys fall back to English, then to the key
 * itself so a missing translation is visible instead of empty.
 */
export function makeT(strings) {
  const map = strings && typeof strings === "object" ? strings : {};
  const t = (key, vars) => {
    const raw = typeof map[key] === "string" ? map[key] : (EN[key] ?? key);
    if (!vars) return raw;
    return raw.replace(/\{(\w+)\}/g, (m, name) => (Object.hasOwn(vars, name) ? String(vars[name]) : m));
  };
  /** Plural lookup: `key.one` for 1, `key.other` otherwise; `{n}` is filled in. */
  t.n = (key, n, vars) => t(`${key}.${n === 1 ? "one" : "other"}`, { ...vars, n });
  return t;
}
