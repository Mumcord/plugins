// Writes two tables the plugin embeds:
// - ../src/items.txt: the English names of EVE's modules, drones, fighters, implants and boosters
//   by where they go on a ship, to sort fits whose blank lines got lost on the way through the
//   chat;
// - ../src/names.txt: the names of the items a fit can hold in the other languages EVE supports,
//   to read fits copied from a non-English EVE client.
//
//   node scripts/items.mjs           write both
//   node scripts/items.mjs --check   fail if either differs
//
// build.mjs runs it as well.

import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import * as flatbuffers from "flatbuffers";
import { loadSde } from "@eveshipfit/sde-loader";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const MODULES = join(ROOT, "node_modules");
export const ITEMS = join(ROOT, "..", "src", "items.txt");
export const NAMES = join(ROOT, "..", "src", "names.txt");

/** Dogma effects that put a module into a slot, in the plugin's section order. */
const SLOT_EFFECTS = [
  ["low", 11],
  ["mid", 13],
  ["high", 12],
  ["rig", 2663],
  ["subsystem", 3772],
];
const DRONE_CATEGORIES = new Set([18, 87]); // drones, fighters
const IMPLANT_CATEGORY = 20; // implants and boosters
/** Categories of what a fit names: ships, modules, charges, drones, implants and boosters,
 * deployables, subsystems, fighters. Other cargo is rare and stays as pasted. */
const FIT_CATEGORIES = new Set([6, 7, 8, 18, 20, 22, 32, 87]);

async function sdeData() {
  const sde = await loadSde({ bytes: new Uint8Array(await readFile(join(MODULES, "@eveshipfit/sde/dist/sde.dat"))) });
  const { version } = JSON.parse(await readFile(join(MODULES, "@eveshipfit/sde/package.json"), "utf8"));
  return { sde, version };
}

/** The text of items.txt for the SDE in node_modules. */
export async function itemsText({ sde, version }) {
  const kinds = new Map([...SLOT_EFFECTS.map(([kind]) => [kind, new Set()]), ["drone", new Set()], ["other", new Set()]]);
  for (const type of sde.types()) {
    // A name on two lines, or one that looks like a section header, could not be looked up.
    if (!type.published || /[\n[\]]/.test(type.name)) continue;
    const slot = SLOT_EFFECTS.find(([, effect]) => type.effectIds.has(effect));
    const kind = slot
      ? slot[0]
      : DRONE_CATEGORIES.has(type.categoryId)
        ? "drone"
        : type.categoryId === IMPLANT_CATEGORY
          ? "other"
          : undefined;
    if (kind) kinds.get(kind).add(type.name.trim());
  }
  const lines = [`# Generated by web-src/scripts/items.mjs from @eveshipfit/sde ${version}; do not edit.`];
  for (const [kind, names] of kinds) {
    lines.push(`[${kind}]`, ...[...names].sort());
  }
  return `${lines.join("\n")}\n`;
}

/**
 * Every name in names.dat with its type ID. The loader only looks names up, so this reads the
 * flatbuffer (specs/names.fbs) directly: field 1 `names` (lowercased per code point), field 2
 * `type_ids`, index for index.
 */
async function localizedNames() {
  const bb = new flatbuffers.ByteBuffer(new Uint8Array(await readFile(join(MODULES, "@eveshipfit/sde/dist/names.dat"))));
  if (!bb.__has_identifier("ESFN")) throw new Error("names.dat is not a Names file");
  const root = bb.readInt32(bb.position()) + bb.position();
  const names = bb.__vector(root + bb.__offset(root, 6));
  const typeIds = bb.__vector(root + bb.__offset(root, 8));
  const count = bb.__vector_len(root + bb.__offset(root, 6));
  const result = [];
  for (let i = 0; i < count; i++) {
    result.push([bb.__string(names + i * 4), bb.readInt32(typeIds + i * 4)]);
  }
  return result;
}

/**
 * The text of names.txt: one line per item a fit can hold whose name differs in another language,
 * `English name<TAB>other name<TAB>…`, the other names lowercased. German and Russian clients use
 * the English names for these items, so the other names are Spanish, French, Japanese, Chinese
 * and Korean. A name that is some item's English name, or that two items share, is left out: it
 * cannot be told apart.
 */
export async function namesText({ sde, version }) {
  const english = new Map();
  const englishLower = new Set();
  for (const type of sde.types()) {
    if (!type.published) continue;
    englishLower.add(type.name.trim().toLowerCase());
    if (FIT_CATEGORIES.has(type.categoryId) && !/[\n[\]]/.test(type.name)) english.set(type.id, type.name.trim());
  }
  const owners = new Map();
  for (const [raw, typeId] of await localizedNames()) {
    // As the plugin looks names up: no-break spaces as spaces, zero-width spaces dropped.
    const name = raw.replaceAll("\u00a0", " ").replaceAll("\u200b", "");
    const en = english.get(typeId);
    if (en === undefined || englishLower.has(name) || /[\n\t[\]]/.test(name)) continue;
    owners.set(name, owners.has(name) && owners.get(name) !== en ? null : en);
  }
  const byEnglish = new Map();
  for (const [name, en] of owners) {
    if (en === null) continue;
    if (!byEnglish.has(en)) byEnglish.set(en, []);
    byEnglish.get(en).push(name);
  }
  const lines = [`# Generated by web-src/scripts/items.mjs from @eveshipfit/sde ${version}; do not edit.`];
  for (const en of [...byEnglish.keys()].sort()) {
    lines.push([en, ...byEnglish.get(en).sort()].join("\t"));
  }
  return `${lines.join("\n")}\n`;
}

export async function writeItems(check) {
  const data = await sdeData();
  for (const [path, text] of [
    [ITEMS, await itemsText(data)],
    [NAMES, await namesText(data)],
  ]) {
    const file = `src/${path.split("/").pop()}`;
    if (!check) {
      await writeFile(path, text);
    } else if ((await readFile(path, "utf8")) !== text) {
      throw new Error(`${file} is not what scripts/items.mjs writes`);
    } else {
      console.log(`${file} matches the data.`);
    }
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeItems(process.argv.includes("--check")).catch((error) => {
    console.error(error.message ?? error);
    process.exit(1);
  });
}
